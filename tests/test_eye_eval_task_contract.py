"""The task fixtures hold for every seed, replay from a result, and admit no free text.

`test_eye_eval_tasks.py` checks the three tasks' properties at a handful of seeds and pins the
default-seed bytes; `test_eye_eval_cross_process_determinism.py` compares separate processes
on one machine. Three things neither covers, and this file does:

* **Every seed, not four.** A tester may pick any seed to counterbalance. The sweep below
  checks a contiguous range plus the 32/63/64-bit boundaries, and that the seed really does
  counterbalance (all six pointer condition orders occur), rather than only that it is legal.
* **Bytes pinned for seeds the checked-in fixtures do not cover.** The suite runs on Linux,
  macOS and Windows (and `scripts/eye_eval_ci.py --with-pytest` selects this file because it
  imports `yazses.eyeeval`), so a digest here is a cross-OS determinism check for
  non-default seeds -- the case a reseeded tester on another machine hits.
* **A result names enough to rebuild its task.** `protocol.{task, task_version, task_seed}`
  is round-tripped through the serialised result and regenerated byte for byte, and the
  helper refuses the cases where guessing would replay a run that never happened.

And one privacy gap closed: a record's few string fields (`block_id`, `block_type`) used to
accept any text, so an outcomes file could carry a window title or a spoken sentence and pass
`check_records`. They are now closed to the task's own vocabulary, and the refusal describes
the value without echoing it.
"""

from __future__ import annotations

import hashlib
import itertools
import json

import pytest

from yazses.eyeeval import (
    EyeEvalTaskError,
    Provenance,
    build_result,
    check_records,
    dump_result,
    dump_task,
    generate_task,
    record_text_vocabulary,
    synthetic_records,
    task_from_protocol,
    validate_result,
    validate_task,
)
from yazses.eyeeval.tasks import (
    FACE_SWITCH_TASK,
    GAZE_SCORED_ROUNDS,
    GAZE_TARGET_COUNT,
    GAZE_TASK,
    HEAD_POINTER_TASK,
    POINTER_CONDITIONS,
    SWITCH_BLOCK_TYPES,
    SWITCH_CUE_COUNT,
    SWITCH_CUE_INTERVAL_MS,
    SWITCH_CUE_JITTER_MS,
    SWITCH_FIRST_CUE_MS,
    TASK_IDS,
    TASK_OUTCOMES,
    TASK_VERSIONS,
)

#: A contiguous range, so no seed is hand-picked to pass, plus the widths where an integer
#: implementation typically breaks: 32-bit, signed 64-bit and unsigned 64-bit edges.
SWEEP = tuple(range(256)) + (2**32 - 1, 2**32, 2**63 - 1, 2**63, 2**64 - 1)

#: SHA-256 of `dump_task(generate_task(task, seed))`, ASCII bytes. Recorded 2026-10-20 on
#: Linux/CPython 3.14. The default seeds are pinned by the checked-in fixtures; these pin
#: three others, so a platform that reorders a reseeded task fails on that platform's leg.
#: A deliberate change to a task regenerates these together with a `task_version` bump.
GOLDEN = {
    (GAZE_TASK, 0): "0dd0a54ed20a33ddd7b83746efe24910ab55b0b1dce993038bf05cc50a1f5ff3",
    (GAZE_TASK, 1): "402f6b70f3557d0016ab4bf665707ea74763888415a86559683e56130d07c4ad",
    (GAZE_TASK, 2**64 - 1): "8e97a8097c67c00c88e8774cc8e349b545e50b47ea97c86abbe0306f9b42b59f",
    (HEAD_POINTER_TASK, 0): "b25296e09a0da2ee96337cf25d0dbffca42d68828f413606578604ffe5049f43",
    (HEAD_POINTER_TASK, 1): "c849ab97b89d6d01f52fb245b85370c2114a7089c11ada33cb67637c58b282de",
    (HEAD_POINTER_TASK, 2**64 - 1): "2eea2b411ae793cc95c615b9b2e39c086f4826259281ed9a98e82da59f9ef671",
    (FACE_SWITCH_TASK, 0): "9caada26b0c5b036fc3026fc800a32a7e3b079aff02dd933b8a6bf4cae0b0c50",
    (FACE_SWITCH_TASK, 1): "b53dc1053e362c50147194703c239413228139e1250fd64e0453ff936f737d09",
    (FACE_SWITCH_TASK, 2**64 - 1): "f1f4eee003488fac1efaf79c5610ec7335b65d3953c285f275f9c48c3fd9aaa2",
}

#: A fixed fake machine: provenance is an input to a result, not something under test here.
MACHINE = Provenance(
    yazses_version="9.9.9", git_commit="0123456789ab", python_version="3.13.0",
    os_name="ExampleOS", os_version="1.2", kernel="0.0.0-test", arch="x86_64",
    cpu_model="Example CPU 1000", logical_cpus=8, ram_gb=16.0, session_type="headless",
    displays=({"index": 0, "x": 0, "y": 0, "width": 1920, "height": 1080,
               "scale": 1.0, "primary": True},),
    packages={"yazses": "9.9.9"},
)

#: What a careless outcomes file might paste into a text field. Never a real person's data.
PRIVATE_TEXT = "Quarterly-salaries.xlsx - Example Office"


def _digest(doc: dict) -> str:
    return hashlib.sha256(dump_task(doc).encode("ascii")).hexdigest()


def _result_for(task: dict) -> dict:
    return build_result(
        task=task, records=synthetic_records(task), provenance=MACHINE,
        study_mode="synthetic", timestamp="2026-10-20T00:00:00+00:00", camera_class="none",
        capture_mode="synthetic_replay", records_source="synthetic",
    )


# --- every seed ---------------------------------------------------------------------


@pytest.mark.parametrize("task_id", TASK_IDS)
def test_every_seed_in_the_sweep_produces_a_valid_task_that_records_its_seed(task_id):
    for seed in SWEEP:
        doc = generate_task(task_id, seed)
        assert validate_task(doc) == [], (task_id, seed, validate_task(doc))
        assert doc["seed"] == seed
        assert doc["task_version"] == TASK_VERSIONS[task_id]


def test_the_gaze_sequence_is_balanced_and_repeat_free_for_every_seed():
    """Checked directly, not only via `validate_task`: a validator bug must not hide a generator bug."""
    for seed in SWEEP:
        trials = generate_task(GAZE_TASK, seed)["blocks"][1]["trials"]
        asked = [t["intended_target_id"] for t in trials]
        assert len(asked) == GAZE_SCORED_ROUNDS * GAZE_TARGET_COUNT, seed
        assert all(asked.count(i) == GAZE_SCORED_ROUNDS for i in range(1, GAZE_TARGET_COUNT + 1)), seed
        assert all(a != b for a, b in itertools.pairwise(asked)), seed


def test_the_face_switch_cues_stay_inside_their_jitter_window_for_every_seed():
    for seed in SWEEP:
        doc = generate_task(FACE_SWITCH_TASK, seed)
        deliberate = next(b for b in doc["blocks"] if b["block_type"] == "deliberate")
        cues = deliberate["cue_times_ms"]
        assert len(cues) == SWITCH_CUE_COUNT, seed
        for index, cue in enumerate(cues):
            nominal = SWITCH_FIRST_CUE_MS + index * SWITCH_CUE_INTERVAL_MS
            assert abs(cue - nominal) <= SWITCH_CUE_JITTER_MS, (seed, index, cue)


def test_the_seed_actually_counterbalances_rather_than_being_decorative():
    """A seed that changed nothing would still pass every validity check above."""
    pointer_orders = {
        tuple((c["radius_permille"], c["target_width_permille"])
              for c in generate_task(HEAD_POINTER_TASK, seed)["condition_order"])
        for seed in SWEEP
    }
    assert pointer_orders == set(itertools.permutations(POINTER_CONDITIONS))

    first_panes = {generate_task(GAZE_TASK, seed)["blocks"][1]["trials"][0]["intended_target_id"]
                   for seed in SWEEP}
    assert first_panes == set(range(1, GAZE_TARGET_COUNT + 1))

    gaze_orders = {tuple(t["intended_target_id"] for t in generate_task(GAZE_TASK, seed)["blocks"][1]["trials"])
                   for seed in SWEEP}
    cue_lists = {tuple(next(b for b in generate_task(FACE_SWITCH_TASK, seed)["blocks"]
                            if b["block_type"] == "deliberate")["cue_times_ms"]) for seed in SWEEP}
    # 40-trial orders and 30-cue jitter vectors have astronomically many values; a collision
    # inside 261 seeds would mean the seed is not reaching the generator.
    assert len(gaze_orders) == len(SWEEP)
    assert len(cue_lists) == len(SWEEP)


def test_the_seed_changes_order_never_geometry_or_vocabulary():
    for task_id in TASK_IDS:
        base = generate_task(task_id, 0)
        other = generate_task(task_id, 1)
        for key in ("records", "outcomes", "task_version", "privacy"):
            assert base[key] == other[key], (task_id, key)
    assert generate_task(GAZE_TASK, 0)["targets"] == generate_task(GAZE_TASK, 1)["targets"]

    def rings(seed: int) -> list:
        return sorted(
            (b["radius_permille"], b["target_width_permille"], json.dumps(b["targets"]))
            for b in generate_task(HEAD_POINTER_TASK, seed)["blocks"]
        )

    assert rings(0) == rings(1), "the conditions are reordered, never resized"


# --- bytes pinned across operating systems -------------------------------------------


@pytest.mark.parametrize(("task_id", "seed"), sorted(GOLDEN), ids=lambda v: str(v))
def test_a_reseeded_task_is_the_same_bytes_on_every_platform(task_id, seed):
    assert _digest(generate_task(task_id, seed)) == GOLDEN[(task_id, seed)]


def test_the_golden_digests_are_distinct_and_cover_every_task():
    """Nine equal digests would mean the seed never reached the bytes being hashed."""
    assert len(set(GOLDEN.values())) == len(GOLDEN)
    assert {task_id for task_id, _ in GOLDEN} == set(TASK_IDS)


# --- a result names enough to replay its task ---------------------------------------


@pytest.mark.parametrize("task_id", TASK_IDS)
@pytest.mark.parametrize("seed", [0, 7, 2**63 + 5])
def test_a_result_round_trips_to_the_exact_task_it_ran(task_id, seed):
    task = generate_task(task_id, seed)
    parsed = json.loads(dump_result(_result_for(task)))
    assert validate_result(parsed) == []
    assert parsed["protocol"]["task_seed"] == seed
    assert parsed["protocol"]["task_version"] == TASK_VERSIONS[task_id]
    assert dump_task(task_from_protocol(parsed["protocol"])) == dump_task(task)


@pytest.mark.parametrize(
    ("change", "why"),
    [
        ({"task_seed": None}, "task_seed"),          # gaze_field reports carry None
        ({"task_seed": True}, "task_seed"),          # a bool is not a seed
        ({"task_seed": -1}, "task_seed"),
        ({"task_seed": 1.0}, "task_seed"),
        ({"task_version": "0.9"}, "task_version"),   # an older protocol cannot be regenerated
        ({"task": "gaze_routing_9_pane"}, "protocol.task"),
    ],
)
def test_a_protocol_that_cannot_name_one_task_is_refused_not_guessed(change, why):
    protocol = {"task": GAZE_TASK, "task_version": TASK_VERSIONS[GAZE_TASK],
                "task_seed": 3, "protocol_id": None}
    protocol.update(change)
    with pytest.raises(EyeEvalTaskError, match=why):
        task_from_protocol(protocol)


def test_a_missing_seed_is_refused_rather_than_defaulted():
    with pytest.raises(EyeEvalTaskError, match="task_seed"):
        task_from_protocol({"task": GAZE_TASK, "task_version": TASK_VERSIONS[GAZE_TASK]})


@pytest.mark.parametrize("protocol", [None, [], "gaze_routing_4_pane"])
def test_a_non_object_protocol_is_refused(protocol):
    with pytest.raises(EyeEvalTaskError, match="protocol"):
        task_from_protocol(protocol)


# --- no free text in a record -------------------------------------------------------


def test_the_text_vocabulary_is_derived_from_the_task_document():
    switch = generate_task(FACE_SWITCH_TASK)
    vocabulary = record_text_vocabulary(switch)
    assert vocabulary["block_id"] == tuple(b["block_id"] for b in switch["blocks"])
    assert vocabulary["block_type"] == SWITCH_BLOCK_TYPES
    assert vocabulary["outcome"] == TASK_OUTCOMES[FACE_SWITCH_TASK]
    for task_id in (GAZE_TASK, HEAD_POINTER_TASK):
        assert record_text_vocabulary(generate_task(task_id)) == {"outcome": TASK_OUTCOMES[task_id]}
    assert record_text_vocabulary({"task_id": "nope"}) == {}


@pytest.mark.parametrize("task_id", TASK_IDS)
def test_the_synthetic_records_use_only_the_vocabulary(task_id):
    """The permissive direction: the closed vocabulary must not refuse a legitimate run."""
    task = generate_task(task_id)
    assert check_records(task, synthetic_records(task)) == []


@pytest.mark.parametrize("field", ["block_id", "block_type"])
@pytest.mark.parametrize("outcome", ["false_activation", None])
def test_free_text_in_a_record_string_field_is_refused_and_not_echoed(field, outcome):
    """A `false_activation` row answers no cue, so the identity check never looked at it --
    which is exactly where pasted text used to pass. A block summary (no outcome) too."""
    task = generate_task(FACE_SWITCH_TASK)
    record: dict = {"block_id": "speaking", "block_type": "speaking"}
    if outcome:
        record["outcome"] = outcome
    else:
        record["false_activation_count"] = 1
    record[field] = PRIVATE_TEXT
    problems = check_records(task, synthetic_records(task) + [record])
    assert any(f".{field}: not a value this task defines" in p for p in problems), problems
    assert not any(PRIVATE_TEXT in p for p in problems), "the refusal must not reprint the text"


@pytest.mark.parametrize("value", [7, ["speaking"], {"x": 1}, None])
def test_a_non_string_block_id_is_refused_without_crashing(value):
    task = generate_task(FACE_SWITCH_TASK)
    record = {"block_id": value, "block_type": "speaking", "false_activation_count": 0}
    problems = check_records(task, [record])
    assert any(".block_id: not a value this task defines" in p for p in problems), problems


def test_a_block_type_that_contradicts_its_block_is_refused():
    """Both values are legal words; together they misattribute a false activation."""
    task = generate_task(FACE_SWITCH_TASK)
    record = {"block_id": "neutral", "block_type": "speaking", "outcome": "false_activation"}
    problems = check_records(task, synthetic_records(task) + [record])
    assert any("is a 'neutral' block, not 'speaking'" in p for p in problems), problems

"""The homepage roadmap preview states status, not a shipping sequence (issue #843).

`docs/roadmap.md` is the canonical, evidence-gated roadmap. The homepage section
`roadmap-at-a-glance` in `overrides/home.html` once kept a second, contradictory
roadmap: "Four eras", an animated progress rail fixed at 55 %, and Android listed as
"Next · under way". These tests keep the section to four independent status cards that
use the roadmap's own status words, and keep every link it makes pointed at a heading
or page that exists.
"""
from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]

# The old timeline vocabulary: markup, CSS hooks and the variable the animation read.
RETIRED = (
    "Four eras",
    "yzl-eras",
    "yzl-era__",
    "yzl-era--",
    "data-yzl-eras",
    "--progress",
    "The horizon",
    "Next · under way",
    "Android dictation keyboard",
    "An offline keyboard in your pocket",
)


def _read(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8")


def _section() -> str:
    html = _read("overrides/home.html")
    match = re.search(r'<section class="yzl-road".*?</section>', html, re.S)
    assert match, "overrides/home.html has no roadmap-at-a-glance section"
    return match.group(0)


def _slug(heading: str) -> str:
    """GitHub's slug as configured for the site's toc extension (pymdownx.slugs, case=lower)."""
    text = heading.strip().lower()
    text = re.sub(r"\{[^}]*\}\s*$", "", text).strip()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def _anchors(markdown_path: str) -> set[str]:
    anchors: set[str] = set()
    for line in _read(markdown_path).splitlines():
        match = re.match(r"#{1,6}\s+(.*)", line)
        if not match:
            continue
        explicit = re.search(r"\{\s*#([\w-]+)\s*\}\s*$", match.group(1))
        anchors.add(explicit.group(1) if explicit else _slug(match.group(1)))
    return anchors


def test_the_timeline_vocabulary_is_gone_from_every_homepage_asset():
    for rel in ("overrides/home.html", "docs/assets/landing.css", "docs/assets/landing.js"):
        text = _read(rel)
        for phrase in RETIRED:
            assert phrase not in text, f"{rel} still contains the retired timeline copy {phrase!r}"


def test_four_independent_cards_each_print_their_status_in_words():
    section = _section()
    cards = re.findall(r'<article class="yzl-fam .*?</article>', section, re.S)
    assert len(cards) == 1, "the cards are generated by one loop over `fams`"
    block = re.search(r"{% set fams = \[(.*?)\] %}", section, re.S)
    assert block, "the card data (`set fams`) moved"
    statuses = re.findall(r'^\s*\("(\w[\w-]*)", "([^"]+)", "([^"]+)"', block.group(1), re.M)
    keys = {key: status for key, status, _name in statuses}
    assert set(keys) == {"released", "released-unverified", "experimental", "research"}
    # The roadmap's own words (docs/roadmap.md, "What our status words mean").
    assert keys["released"].startswith("Released")
    assert keys["released-unverified"].startswith("Released")
    assert "real-client" in keys["released-unverified"]
    assert keys["experimental"].startswith("Experimental")
    assert "hardware-unverified" in keys["experimental"]
    assert "Research" in keys["research"] and "Deferred" in keys["research"]
    # Status is a visible text node, not only a colour.
    assert 'class="yzl-fam__status"' in section


def test_no_order_cue_numbers_or_percentages_in_the_section():
    section = _section()
    assert "<ol" not in section
    assert "aria-hidden=\"true\"><span></span>" not in section
    assert not re.search(r"\d+\s?%", section), "a percentage implies progress"
    assert not re.search(r"\bv3\b", section)
    css = _read("docs/assets/landing.css")
    assert "yzl-fam" in css
    assert "calc(var(--progress)" not in css


def test_the_claims_the_roadmap_denies_stay_denied():
    flat = " ".join(re.sub(r"<[^>]+>", " ", _section()).split())
    assert "no installable app or APK" in flat
    assert "never sends it" in flat
    assert "not yet been tried in the real Claude or Codex apps" in flat
    assert "not medical devices" in flat
    assert "Semantic, cited recall: research only" in flat
    assert "official MCP registry" in flat
    # Nothing in the section may promise the thing the roadmap says does not exist.
    assert not re.search(r"Android (app|keyboard) (is )?(available|shipped|coming)", flat, re.I)


def test_every_roadmap_and_validation_link_resolves_to_a_real_heading():
    section = _section()
    docs = {"roadmap.html": "docs/roadmap.md"}
    seen = 0
    for target in re.findall(r"['\"]((?:roadmap|validation-matrix|mobile/index|how-to/biosignal-hardware)\.html[^'\"]*)['\"]", section):
        page, _, fragment = target.partition("#")
        source = docs.get(page, "docs/" + page.removesuffix(".html") + ".md")
        assert (ROOT / source).is_file(), f"{target} points at a missing page {source}"
        if fragment:
            assert fragment in _anchors(source), f"{target}: no heading with anchor #{fragment} in {source}"
        seen += 1
    assert seen >= 8, "the cards and the legend should link the canonical pages"
    # The legend links the status-words heading through the `url` filter form.
    assert "roadmap.html' | url }}#what-our-status-words-mean" in section
    assert "what-our-status-words-mean" in _anchors("docs/roadmap.md")


def test_milestone_labels_in_the_section_do_not_promise_an_android_app():
    section = _section()
    assert "Source foundations only; no app yet" in section

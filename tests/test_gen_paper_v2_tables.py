# --- --check fails when the artifacts drift, and the generator stops on bad input ----------


def test_check_goes_from_current_to_failing_when_one_artifact_number_changes(tree, capsys):
    out = tree / "gen"
    assert gen.main(["--root", str(tree), "--out-dir", str(out)]) == 0
    assert gen.main(["--root", str(tree), "--out-dir", str(out), "--check"]) == 0

    def bump(d):
        d["result"]["models"]["parakeet-tdt-0.6b-v2"]["wer"] = 9.99

    _edit_json(tree / "paper/results/probes/wer-vm-clean.json", bump)
    capsys.readouterr()
    assert gen.main(["--root", str(tree), "--out-dir", str(out), "--check"]) == 1
    err = capsys.readouterr().err
    assert "clean_asr.tex" in err and "stale" in err
    # ... and it is the new number that is rendered, not the old one
    assert "9.99" in gen.build_all(tree)["clean_asr.tex"]


def test_check_fails_on_a_hand_edited_generated_file(tree, capsys):
    out = tree / "gen"
    assert gen.main(["--root", str(tree), "--out-dir", str(out)]) == 0
    target = out / "streaming.tex"
    target.write_text(target.read_text(encoding="utf-8").replace("1.377", "1.000"), encoding="utf-8")
    assert gen.main(["--root", str(tree), "--out-dir", str(out), "--check"]) == 1


def test_check_fails_on_a_stray_file_the_generator_does_not_produce(tree):
    out = tree / "gen"
    assert gen.main(["--root", str(tree), "--out-dir", str(out)]) == 0
    (out / "hand_written.tex").write_text("x", encoding="utf-8")
    assert gen.main(["--root", str(tree), "--out-dir", str(out), "--check"]) == 1


def test_crlf_checkout_of_an_artifact_does_not_change_the_output(tree):
    # Start from LF whatever the checkout gave: on a Windows runner the file may already be
    # CRLF, and converting "\n" again would write "\r\r\n", which no checkout produces.
    p = tree / "paper/results/streaming.json"
    lf = p.read_bytes().replace(b"\r\n", b"\n")
    p.write_bytes(lf)
    baseline = gen.build_all(tree)
    p.write_bytes(lf.replace(b"\n", b"\r\n"))
    assert gen.build_all(tree) == baseline


def test_a_missing_artifact_exits_2_and_writes_nothing(tree, capsys):
    (tree / "paper/results/streaming.json").unlink()
    out = tree / "gen"
    assert gen.main(["--root", str(tree), "--out-dir", str(out)]) == 2
    assert not out.exists()


def test_a_malformed_artifact_exits_2(tree):
    (tree / "paper/results/onset.json").write_text("{not json", encoding="utf-8")
    assert gen.main(["--root", str(tree), "--out-dir", str(tree / "gen")]) == 2


def test_an_empty_platform_archive_is_an_error_not_an_empty_table(tree):
    shutil.rmtree(tree / "paper/results/platforms")
    (tree / "paper/results/platforms").mkdir()
    with pytest.raises(gen.GenError):
        gen.build_all(tree)
    assert gen.main(["--root", str(tree), "--out-dir", str(tree / "gen")]) == 1


def test_two_sweeps_that_disagree_on_one_threshold_stop_the_generator(tree):
    def corrupt(d: dict[str, Any]) -> None:
        for p in d["result"]["sweep"]:
            if p["cluster_threshold"] == 0.7:
                p["der"] = 99.0

    _edit_json(tree / "paper/results/probes/synth-sweep-wide.json", corrupt)
    with pytest.raises(gen.GenError, match="refusing to pick one"):
        gen.build_all(tree)


def test_an_unparseable_hard_run_log_is_an_error_not_a_silently_missing_run(tree):
    (tree / "paper/results/probes/logs/x86b-other_wer.log").write_text("nothing here\n", encoding="utf-8")
    with pytest.raises(gen.GenError):
        gen.build_all(tree)


def test_tex_escaping_handles_the_characters_artifact_text_contains():
    assert gen.esc("a_b & 5% #1 {x}") == r"a\_b \& 5\% \#1 \{x\}"
    assert gen.sg(-1.5, 1) == "$-$1.5" and gen.sg(2.0, 1) == "+2.0"
    assert gen.rng(3.0, 3.001) == "3.00" and gen.rng(3.0, 3.5) == "3.00--3.50"

"""The paper-v2 tables and figure data are generated from the archived result files (#508).

`design/publication/paper-v2/manuscript/generated/` is written by
`scripts/gen-paper-v2-tables.py` from `paper/results/` and committed. This file guards the
failure shapes this repository has met before, then the issue's own acceptance criteria.

**An "is it in sync?" test cannot notice an omission.** Regenerating and diffing only proves
the output matches its generator, so a generator that silently drops an engine, a runner or a
run agrees with its own output. Completeness is therefore asserted against the *artifacts*:
every engine in the JSON is a row in the data file, every runner directory is a column, every
disagreeing run is present, and the drop is simulated so the assertion is known to fire.

**A check that cannot parse its input must fail loudly.** A missing or malformed artifact exits
2 and writes nothing; two artifacts that contradict each other on one point stop the generator
(exit 1) instead of letting it pick one.

**A drift test must be shown to fail.** The artifacts are copied into ``tmp_path``, one number
is changed, and ``--check`` must go from 0 to 1.

Everything here reads the repository and writes only inside ``tmp_path``.
"""

from __future__ import annotations

import ast
import csv
import hashlib
import importlib.util
import io
import json
import re
import shutil
import sys
from pathlib import Path
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "gen-paper-v2-tables.py"
GENERATED = ROOT / "design" / "publication" / "paper-v2" / "manuscript" / "generated"
RESULTS = ROOT / "paper" / "results"


def _load():
    """Load the hyphenated script as a module, registered before it executes."""
    name = "gen_paper_v2_tables"
    spec = importlib.util.spec_from_file_location(name, SCRIPT)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


gen = _load()


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def _csv_rows(text: str) -> list[dict[str, str]]:
    body = "\n".join(ln for ln in text.splitlines() if not ln.startswith("#"))
    return list(csv.DictReader(io.StringIO(body)))


@pytest.fixture()
def tree(tmp_path: Path) -> Path:
    """A private copy of the result archive, so a test can change one number."""
    shutil.copytree(RESULTS, tmp_path / "paper" / "results")
    return tmp_path


def _edit_json(path: Path, mutate) -> None:
    doc = json.loads(path.read_text(encoding="utf-8"))
    mutate(doc)
    path.write_text(json.dumps(doc), encoding="utf-8")


# --- the committed output is current, complete and deterministic ---------------------------


def test_the_generator_is_importable_and_produces_files():
    assert len(gen.build_all(ROOT)) >= 15


def test_the_committed_outputs_are_current(capsys):
    assert gen.main(["--check"]) == 0, capsys.readouterr().err


def test_the_committed_directory_has_no_stray_or_missing_file():
    expected = set(gen.build_all(ROOT))
    on_disk = {p.name for p in GENERATED.iterdir() if p.is_file()}
    assert on_disk == expected


def test_output_is_byte_identical_on_a_rerun(tmp_path):
    out = tmp_path / "gen"
    assert gen.main(["--out-dir", str(out)]) == 0
    first = {p.name: p.read_bytes() for p in out.iterdir()}
    assert gen.main(["--out-dir", str(out)]) == 0
    second = {p.name: p.read_bytes() for p in out.iterdir()}
    assert first == second
    assert first == {n: b.encode("utf-8") for n, b in gen.build_all(ROOT).items()}


def test_every_file_is_marked_generated_and_names_its_sources_with_real_hashes():
    for path in sorted(GENERATED.iterdir()):
        text = path.read_text(encoding="utf-8")
        assert "GENERATED by scripts/gen-paper-v2-tables.py -- DO NOT EDIT" in text, path.name
        pairs = re.findall(r"^[%#]   (\S+)  sha256:([0-9a-f]{64})$", text, re.M)
        assert pairs, f"{path.name} lists no source artifact"
        for rel, sha in pairs:
            assert (ROOT / rel).is_file(), f"{path.name} cites a missing artifact {rel}"
            assert _sha(ROOT / rel) == sha, f"{path.name}: sha256 of {rel} is stale"
            assert rel.startswith("paper/results/"), f"{path.name} reads outside the archive: {rel}"


def test_tables_name_their_sources_in_the_caption_or_a_note():
    for path in sorted(GENERATED.glob("*.tex")):
        text = path.read_text(encoding="utf-8")
        assert "\\label{tab:" in text, path.name
        assert "paper/\\allowbreak{}results/" in text, f"{path.name} names no source artifact"


def test_the_script_holds_no_typed_result_numbers():
    """The only float literal allowed is the percent scaling; results come from artifacts."""
    tree_ = ast.parse(SCRIPT.read_text(encoding="utf-8"))
    floats = {
        n.value
        for n in ast.walk(tree_)
        if isinstance(n, ast.Constant) and isinstance(n.value, float)
    }
    assert floats <= {100.0}, floats


# --- faithful: the data files equal the artifacts, in both directions -----------------------


def test_robustness_data_equals_the_artifacts_for_every_engine_and_every_run():
    rows = {r["engine"]: r for r in _csv_rows((GENERATED / "robustness.csv").read_text(encoding="utf-8"))}
    a = json.loads((RESULTS / "probes/wer-matrix.json").read_text(encoding="utf-8"))["result"]["models"]
    b = json.loads((RESULTS / "probes/wer-vm-clean.json").read_text(encoding="utf-8"))["result"]["models"]
    h2 = json.loads((RESULTS / "wer-test-other.json").read_text(encoding="utf-8"))["models"]
    log = (RESULTS / "probes/logs/x86b-other_wer.log").read_text(encoding="utf-8")
    h1 = {
        m.group(1): float(m.group(2))
        for m in re.finditer(r"^\[wer\] (\S+): WER=([\d.]+)%", log, re.M)
    }
    # completeness: nothing in the artifact is missing from the data file
    assert set(rows) == set(a) == set(b) == set(h2) == set(h1)
    for k, r in rows.items():
        assert float(r["clean_wer_run_a"]) == a[k]["wer"]
        assert float(r["clean_wer_run_b"]) == b[k]["wer"]
        assert float(r["hard_wer_run_1_log"]) == h1[k]
        assert float(r["hard_wer_run_2"]) == h2[k]["wer"]
        pairs = [h / c for h in (h1[k], h2[k]["wer"]) for c in (a[k]["wer"], b[k]["wer"])]
        assert float(r["hard_over_clean_min"]) == pytest.approx(min(pairs), abs=0.006)
        assert float(r["hard_over_clean_max"]) == pytest.approx(max(pairs), abs=0.006)


def test_contradictory_runs_are_both_shown_not_one_selected():
    """large-v3 hard: 4.86 (log) vs 7.69 (JSON); the table must carry the span, and so must the data."""
    hard = (GENERATED / "hard_asr.tex").read_text(encoding="utf-8")
    assert re.search(r"large-v3\}[^&]*& 3\.23--3\.41 & 4\.86--7\.69 &", hard)
    clean = (GENERATED / "clean_asr.tex").read_text(encoding="utf-8")
    assert "3.41 (A) vs 3.23 (B)" in clean
    lv3 = _csv_rows((GENERATED / "largev3_repeats.csv").read_text(encoding="utf-8"))
    other = [r for r in lv3 if r["split"] == "test-other"]
    assert len(other) == 2 + 4 + 5 + 3  # matrix x2, probe x4, determinism baseline x5, arms x3
    assert {r["substitutions"] for r in other if r["substitutions"]} == {"87"}
    assert {r["deletions"] for r in other if r["deletions"]} == {"15"}
    contexts = {r["context"] for r in other}
    assert len(contexts) == 4, "contexts must stay separate, not pooled"



"""Turn paper/results/*.json into LaTeX tables (figures/*.tex) and vector figures.

Run after run_all.py. Every table/figure the paper \\input's or \\includegraphics is
generated here, so no measured number is ever transcribed by hand.
"""
from __future__ import annotations

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from _common import PAPER_DIR, RESULTS_DIR

FIG_DIR = PAPER_DIR / "figures"
MODELS = ["tiny.en", "base.en", "small.en"]
# Colorblind-safe (Wong)
BLUE, ORANGE, GREEN = "#0072B2", "#E69F00", "#009E73"

plt.rcParams.update(
    {
        "font.size": 10,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "figure.dpi": 150,
        "savefig.bbox": "tight",
    }
)


def _load(name: str) -> dict:
    return json.loads((RESULTS_DIR / f"{name}.json").read_text())


def _fmt(x, nd=1):
    return f"{x:.{nd}f}"


def table_main(wer, latency, meta) -> str:
    # RTF (from the WER sample) is the sample-robust, duration-normalized speed metric;
    # we do not put absolute decode-ms here because it is measured on a different
    # (timing) subset and scales with clip length. Load/RSS/disk are sample-robust.
    foot = meta["model_footprint_mb"]
    rows = []
    for m in MODELS:
        w = wer["models"][m]
        lat = latency["models"][m]
        disk = foot.get(m, float("nan"))
        rows.append(
            f"{m.replace('_', chr(92) + '_')} & {_fmt(w['wer'],2)} & "
            f"{_fmt(w['rtf_median'],3)} & {_fmt(w['realtime_speedup_median'],1)}$\\times$ & "
            f"{_fmt(lat['cold_start_load_s'],1)} & "
            f"{_fmt(lat['model_rss_delta_mb'],0)} & {_fmt(disk,0)} \\\\"
        )
    body = "\n".join(rows)
    return (
        "% AUTO-GENERATED by make_figures.py -- do not edit\n"
        "\\begin{tabular}{lrrrrrr}\n\\toprule\n"
        "Model & WER & RTF & Speed & Load & RSS & Disk \\\\\n"
        " & (\\%) & (med.) & & (s) & (MB) & (MB) \\\\\n"
        "\\midrule\n"
        f"{body}\n"
        "\\bottomrule\n\\end{tabular}\n"
    )


def table_pipeline(latency) -> str:
    st = latency["pipeline_stages"]
    label = {
        "vad_gate": "VAD gate (RMS)",
        "clean_text": "Text cleanup",
        "disfluency_filter": "Disfluency filter",
        "grammar_classify_dictation": "Grammar classify (dictation)",
        "grammar_classify_command": "Grammar classify (command)",
    }
    rows = [
        f"{label[k]} & {st[k]['median_ms']:.4f} & {st[k]['p95_ms']:.4f} \\\\"
        for k in label
    ]
    body = "\n".join(rows)
    total = latency["non_decode_overhead_median_ms"]
    return (
        "% AUTO-GENERATED by make_figures.py -- do not edit\n"
        "\\begin{tabular}{lrr}\n\\toprule\n"
        "Pipeline stage & Median (ms) & P95 (ms) \\\\\n\\midrule\n"
        f"{body}\n\\midrule\n"
        f"\\textbf{{Total non-decode overhead}} & \\textbf{{{total:.3f}}} & \\\\\n"
        "\\bottomrule\n\\end{tabular}\n"
    )


def newcommands(wer, latency, commands, vad, meta) -> str:
    """LaTeX macros for inline numbers, so prose never hard-codes a measurement."""
    prov = wer["provenance"]
    # psutil reports OS-visible total (a bit below installed capacity after reserved
    # memory); report the nominal installed size by rounding GiB to the nearest 4 GiB.
    _ram_gib = prov["ram_gb"] / 1.073741824
    _ram_nominal = int(round(_ram_gib / 4.0) * 4)
    sc = meta["engineering_scale"]
    dg = meta["dysfluency_gate"]
    cp = commands["precision"]
    cf = commands["false_positive"]
    cr = commands["runtime"]
    vr = vad["results"]
    defs = {
        "CPUModel": prov["cpu_model"],
        "NumCPUs": str(prov["logical_cpus"]),
        "RAMGB": str(_ram_nominal),
        "OSName": prov["os"],
        "PyVer": prov["python"],
        "FWVer": prov["faster_whisper"],
        "WERn": str(wer["config"]["n_utterances"]),
        "WERspeakers": str(wer["config"].get("n_speakers", "?")),
        "WERaudioMin": _fmt(wer["config"]["total_audio_seconds"] / 60, 1),
        "WERtiny": _fmt(wer["models"]["tiny.en"]["wer"], 2),
        "WERbase": _fmt(wer["models"]["base.en"]["wer"], 2),
        "WERsmall": _fmt(wer["models"]["small.en"]["wer"], 2),
        "RTFtiny": _fmt(wer["models"]["tiny.en"]["rtf_median"], 3),
        "RTFbase": _fmt(wer["models"]["base.en"]["rtf_median"], 3),
        "RTFsmall": _fmt(wer["models"]["small.en"]["rtf_median"], 3),
        "SpeedTiny": _fmt(wer["models"]["tiny.en"]["realtime_speedup_median"], 1),
        "SpeedSmall": _fmt(wer["models"]["small.en"]["realtime_speedup_median"], 1),
        "DecodeMedSmall": _fmt(latency["models"]["small.en"]["decode_median_ms"], 0),
        "RSSsmall": _fmt(latency["models"]["small.en"]["rss_peak_mb"], 0),
        "Overhead": _fmt(latency["non_decode_overhead_median_ms"], 3),
        "CmdAcc": _fmt(cp["action_accuracy_pct"], 0),
        "CmdAsCmd": _fmt(cp["classified_as_command_pct"], 1),
        "CmdFPR": _fmt(cf["false_positive_rate_pct"], 1),
        "CmdMs": _fmt(cr["per_call_median_ms"], 3),
        "CmdN": str(commands["config"]["n_command_phrases"]),
        "DictN": str(commands["config"]["n_dictation_lines"]),
        "VADspeech": _fmt(vr["speech_detection_rate_pct"], 1),
        "VADsilence": _fmt(vr["silence_rejection_rate_pct"], 1),
        "VADmargin": _fmt(vr["speech_rms_to_threshold_margin_x"], 1),
        "DysFP": _fmt(dg["false_collapse_rate_pct"], 1),
        "DysRecall": _fmt(dg["recall_pct"], 1),
        "DysNclean": str(dg["n_clean_control"]),
        "DysNdys": str(dg["n_dysfluent"]),
        "TestFiles": str(sc["test_files"]),
        "TestFuncs": f"{sc['test_functions']:,}",
        "ADRs": str(sc["adr_files"]),
        "SLOC": f"{sc['src_lines']:,}",
        "SrcFiles": str(sc["src_python_files"]),
    }

    def esc(v: str) -> str:
        return v.replace("_", "\\_").replace("%", "\\%")

    lines = ["% AUTO-GENERATED by make_figures.py -- do not edit"]
    for k, v in defs.items():
        lines.append(f"\\newcommand{{\\yz{k}}}{{{esc(str(v))}}}")
    return "\n".join(lines) + "\n"


def fig_wer(wer):
    fig, ax1 = plt.subplots(figsize=(5.2, 3.0))
    wers = [wer["models"][m]["wer"] for m in MODELS]
    rtfs = [wer["models"][m]["rtf_median"] for m in MODELS]
    x = range(len(MODELS))
    bars = ax1.bar(x, wers, color=BLUE, width=0.55, label="WER (\\%)")
    ax1.set_ylabel("Word error rate (%)", color=BLUE)
    ax1.tick_params(axis="y", labelcolor=BLUE)
    ax1.set_xticks(list(x))
    ax1.set_xticklabels(MODELS)
    for b, w in zip(bars, wers):
        ax1.text(b.get_x() + b.get_width() / 2, w, f"{w:.1f}", ha="center", va="bottom", fontsize=9)
    ax2 = ax1.twinx()
    ax2.plot(list(x), rtfs, "o-", color=ORANGE, label="RTF (median)")
    ax2.set_ylabel("Real-time factor (lower = faster)", color=ORANGE)
    ax2.tick_params(axis="y", labelcolor=ORANGE)
    ax2.spines["top"].set_visible(False)
    ax1.set_title("Accuracy vs. speed across model sizes (CPU int8)")
    fig.savefig(FIG_DIR / "wer.pdf")
    plt.close(fig)


def fig_latency(latency):
    st = latency["pipeline_stages"]
    keys = ["vad_gate", "clean_text", "disfluency_filter", "grammar_classify_dictation"]
    labels = ["VAD gate", "Text cleanup", "Disfluency", "Grammar"]
    meds = [st[k]["median_ms"] for k in keys]
    fig, ax = plt.subplots(figsize=(5.2, 2.8))
    ax.barh(labels, meds, color=GREEN)
    ax.set_xscale("log")
    ax.set_xlabel("Median time per call (ms, log scale)")
    for i, v in enumerate(meds):
        ax.text(v, i, f" {v:.4f}", va="center", fontsize=8)
    ax.set_title("Per-stage cost of the non-decode pipeline")
    fig.savefig(FIG_DIR / "latency.pdf")
    plt.close(fig)


def main():
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    wer = _load("wer")
    latency = _load("latency")
    commands = _load("commands")
    vad = _load("vad")
    meta = _load("meta")

    (FIG_DIR / "tab_main.tex").write_text(table_main(wer, latency, meta))
    (FIG_DIR / "tab_pipeline.tex").write_text(table_pipeline(latency))
    (FIG_DIR / "numbers.tex").write_text(newcommands(wer, latency, commands, vad, meta))
    fig_wer(wer)
    fig_latency(latency)
    print("[figures] wrote tab_main.tex, tab_pipeline.tex, numbers.tex, wer.pdf, latency.pdf")


if __name__ == "__main__":
    main()

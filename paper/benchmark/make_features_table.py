"""Generate the capability-surface table for the paper from the live feature registry.

Reads yazses.system.features (the same registry that backs `yazses features`) and
emits:
  figures/tab_features.tex   - category x tier count table
  figures/features_prose.tex - generated \\newcommand macros naming the default-on
                               and experimental capabilities, so the paper's prose
                               can never drift from the code.
Run from the repo root: uv run python paper/benchmark/make_features_table.py
"""
from __future__ import annotations

from pathlib import Path

PAPER_DIR = Path(__file__).resolve().parents[1]
FIG_DIR = PAPER_DIR / "figures"

TIERS = ("core", "on", "rec", "opt", "exp")


def _esc(s: str) -> str:
    return (
        s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
        .replace("#", "\\#").replace("↔", "--")
    )


def main() -> None:
    from yazses.config import Config
    from yazses.system.features import grouped_features

    cfg = Config()
    groups = grouped_features(cfg)

    rows = []
    totals = {t: 0 for t in TIERS}
    grand = 0
    experimental: list[str] = []
    default_on: list[str] = []
    for cat, _blurb, feats in groups:
        counts = {t: 0 for t in TIERS}
        for f in feats:
            counts[f.tier] = counts.get(f.tier, 0) + 1
            totals[f.tier] = totals.get(f.tier, 0) + 1
            if f.tier == "exp":
                experimental.append(f.name)
            if f.tier in ("core", "on"):
                default_on.append(f.name)
        grand += len(feats)
        default = counts["core"] + counts["on"]
        rows.append(
            f"{_esc(cat)} & {len(feats)} & {default} & {counts['rec']} & "
            f"{counts['opt']} & {counts['exp']} \\\\"
        )
    default_total = totals["core"] + totals["on"]
    body = "\n".join(rows)

    table = (
        "% AUTO-GENERATED by make_features_table.py from yazses.system.features -- do not edit\n"
        "\\begin{tabular}{lrrrrr}\n\\toprule\n"
        "Category & Total & Default & Recomm. & Opt-in & Experim. \\\\\n"
        "\\midrule\n"
        f"{body}\n"
        "\\midrule\n"
        f"\\textbf{{All categories}} & \\textbf{{{grand}}} & {default_total} & "
        f"{totals['rec']} & {totals['opt']} & {totals['exp']} \\\\\n"
        "\\bottomrule\n\\end{tabular}\n"
    )
    (FIG_DIR / "tab_features.tex").write_text(table)

    def _join(names: list[str]) -> str:
        escaped = [_esc(n) for n in names]
        if len(escaped) > 1:
            return ", ".join(escaped[:-1]) + ", and " + escaped[-1]
        return escaped[0] if escaped else ""

    prose = (
        "% AUTO-GENERATED by make_features_table.py -- do not edit\n"
        f"\\newcommand{{\\yzFeatTotal}}{{{grand}}}\n"
        f"\\newcommand{{\\yzFeatDefault}}{{{default_total}}}\n"
        f"\\newcommand{{\\yzFeatRec}}{{{totals['rec']}}}\n"
        f"\\newcommand{{\\yzFeatOpt}}{{{totals['opt']}}}\n"
        f"\\newcommand{{\\yzFeatExp}}{{{totals['exp']}}}\n"
        f"\\newcommand{{\\yzFeatDefaultNames}}{{{_join(default_on)}}}\n"
        f"\\newcommand{{\\yzFeatExpNames}}{{{_join(experimental)}}}\n"
    )
    (FIG_DIR / "features_prose.tex").write_text(prose)
    print(
        f"[features] {grand} capabilities: default {default_total}, rec {totals['rec']}, "
        f"opt {totals['opt']}, exp {totals['exp']} -> tab_features.tex + features_prose.tex"
    )


if __name__ == "__main__":
    main()

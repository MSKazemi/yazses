# Figure 4 — measured decode latency
# --------------------------------------------------------------------------- #
def fig_latency(bench: dict) -> str:
    models = ["tiny.en", "base.en", "small.en"]
    px, pw = 152, 452
    top, rh, rgap = 78, 32, 26
    bottom = top + len(models) * (rh + rgap) - rgap
    H = bottom + 44
    axis_max = 9000.0
    sc = pw / axis_max
    b: list[str] = []

    b.append(f'<rect class="yz-swatch yz-bar--ship" x="{px:g}" y="24" width="11" height="11" rx="3"/>')
    b.append(text(px + 18, 34, "median decode", "yz-l"))
    b.append(f'<rect class="yz-swatch yz-bar--tail" x="{px + 150:g}" y="24" width="11" height="11" rx="3"/>')
    b.append(text(px + 168, 34, "out to the 95th percentile", "yz-l"))
    b.append(text(px, 56, "one utterance · 30 measured · median audio duration 7.3 s", "yz-s"))

    for t in range(0, 10, 2):
        x = px + t * 1000 * sc
        b.append(f'<path class="yz-grid" d="M {x:g} {top - 6:g} L {x:g} {bottom + 4:g}"/>')
        b.append(text(x, bottom + 20, f"{t} s", "yz-m", "middle"))
    b.append(text(px + pw / 2, bottom + 38, "time from release of the key to text on screen", "yz-m", "middle"))

    for i, name in enumerate(models):
        m = bench["models"][name]
        y = top + i * (rh + rgap)
        med, p95 = m["median_ms"] * sc, m["p95_ms"] * sc
        label = name + (" (default)" if name == "base.en" else "")
        fit(label, SZ_L, px - 14, "latency row label")
        b.append(text(px - 14, y + rh / 2 - 2, label, "yz-l", "end"))
        b.append(text(px - 14, y + rh / 2 + 13, f"cold start {m['cold_s']:.2f} s", "yz-m", "end"))

        b.append('<g class="yz-node">' + tip(f"{name} — 95th percentile {m['p95_ms'] / 1000:.2f} s"))
        b.append(
            f'<rect class="yz-bar yz-bar--tail" x="{px:g}" y="{y:g}" width="{p95:g}" '
            f'height="{rh:g}" rx="4" style="--yz-delay:{i * 0.08:g}s"/>'
        )
        b.append("</g>")
        b.append('<g class="yz-node">' + tip(f"{name} — median {m['median_ms'] / 1000:.2f} s"))
        b.append(
            f'<rect class="yz-bar yz-bar--ship" x="{px:g}" y="{y:g}" width="{med:g}" '
            f'height="{rh:g}" rx="4" style="--yz-delay:{i * 0.08:g}s"/>'
        )
        b.append("</g>")
        b.append(text(px + p95 + 10, y + rh / 2 + 4, f"{m['median_ms'] / 1000:.2f} s median", "yz-v"))

    b.append(text(W - 18, H - 6, bench["machine"], "yz-m", "end"))
    return svg(
        "latency",
        H,
        "Measured decode latency per model",
        "Horizontal bars, median and 95th percentile. "
        + "; ".join(
            f"{n}: median {bench['models'][n]['median_ms'] / 1000:.2f} seconds, "
            f"95th percentile {bench['models'][n]['p95_ms'] / 1000:.2f} seconds, "
            f"cold start {bench['models'][n]['cold_s']:.2f} seconds"
            for n in models
        )
        + ". Accuracy improves down the list while latency worsens, which is the trade-off.",
        b,
    )



# Figure 4 — what is wired and what is designed
# --------------------------------------------------------------------------- #
def fig_capabilities(rows: list[tuple[str, int, int]]) -> str:
    rows = sorted(rows, key=lambda r: r[1] + r[2], reverse=True)
    total = sum(w + p for _n, w, p in rows)
    wired = sum(w for _n, w, _p in rows)

    px, pw = 250, W - 250 - 46
    top, rh, rgap = 84, 24, 11
    axis_max = 35  # a round ceiling just above the largest category
    sc = pw / axis_max
    bottom = top + len(rows) * (rh + rgap) - rgap
    H = bottom + 46
    b: list[str] = []

    # Two series, so a legend is always present — and every segment is also
    # direct-labelled with its count, so identity never rests on hue alone.
    b.append(f'<rect class="yz-swatch yz-bar--ship" x="{px:g}" y="26" width="11" height="11" rx="3"/>')
    b.append(text(px + 18, 36, f"wired and working — {wired}", "yz-l"))
    b.append(f'<rect class="yz-swatch yz-bar--plan" x="{px + 210:g}" y="26" width="11" height="11" rx="3"/>')
    b.append(text(px + 228, 36, f"designed, not wired — {total - wired}", "yz-l"))
    b.append(text(px, 58, f"all {total} capabilities in the registry, by category", "yz-s"))

    # Recessive hairline grid — solid, never dashed.
    for t in range(0, axis_max + 1, 5):
        x = px + t * sc
        b.append(f'<path class="yz-grid" d="M {x:g} {top - 6:g} L {x:g} {bottom + 4:g}"/>')
        b.append(text(x, bottom + 22, str(t), "yz-m", "middle"))
    b.append(text(px + pw / 2, bottom + 40, "capabilities", "yz-m", "middle"))

    for i, (name, w, p) in enumerate(rows):
        y = top + i * (rh + rgap)
        fit(name, SZ_L, px - 14, "capability row label")
        b.append(text(px - 14, y + rh / 2 + 4, name, "yz-l", "end"))
        ww, pwid, delay = w * sc, p * sc, i * 0.06

        b.append(f'<g class="yz-node">{tip(f"{name} — {w} wired and working")}')
        b.append(
            f'<rect class="yz-bar yz-bar--ship" x="{px:g}" y="{y:g}" width="{ww:g}" '
            f'height="{rh:g}" rx="4" style="--yz-delay:{delay:g}s"/>'
        )
        b.append("</g>")
        if p:
            # A 2 px surface gap between the two segments — not a border.
            b.append(f'<g class="yz-node">{tip(f"{name} — {p} designed, not yet wired")}')
            b.append(
                f'<rect class="yz-bar yz-bar--plan" x="{px + ww + 2:g}" y="{y:g}" '
                f'width="{max(pwid - 2, 1):g}" height="{rh:g}" rx="4" style="--yz-delay:{delay:g}s"/>'
            )
            b.append("</g>")

        # Direct labels: inside the segment only when they fit with padding.
        if ww >= 26:
            b.append(text(px + ww - 8, y + rh / 2 + 4, str(w), "yz-v yz-on-ship", "end"))
        else:
            b.append(text(px + ww + 6, y + rh / 2 + 4, str(w), "yz-v"))
        if p:
            if pwid >= 26:
                b.append(text(px + ww + pwid - 8, y + rh / 2 + 4, str(p), "yz-v yz-on-plan", "end"))
            else:
                b.append(text(px + ww + pwid + 6, y + rh / 2 + 4, str(p), "yz-v"))

    return svg(
        "capabilities",
        H,
        "Capabilities by category: wired versus designed",
        f"A stacked bar per category. Of {total} registered capabilities, {wired} are wired and "
        f"working and {total - wired} are designed but not yet wired into the build. "
        + "; ".join(f"{n}: {w} wired, {p} designed" for n, w, p in rows)
        + ".",
        b,
    )



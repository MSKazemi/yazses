#!/usr/bin/env python3
"""Generate the architecture figures for docs/architecture.md.

    docs/assets/arch/system-map.svg     the subsystem map, status-coded
    docs/assets/arch/pipeline-heat.svg  the dictation pipeline, coloured by measured cost
    docs/assets/arch/capabilities.svg   140 capabilities: wired vs designed-not-built
    docs/assets/arch/latency.svg        measured decode latency per model

Run:  uv run python scripts/gen-arch-figures.py

Every number in these figures comes from something that can be checked:

  * capability counts come from the live registry (`yazses.system.features`) —
    the same one `yazses features` prints, so a figure claiming a capability is
    wired is making the claim the CLI makes;
  * every timing comes from `docs/benchmarks.md`, parsed at generation time, so
    a figure cannot disagree with the benchmark table a reader can scroll to.
    `paper/` (where the raw JSON lives) is gitignored, so the published page is
    the tracked source of truth;
  * command counts come from the generated `docs/command-index.md`;
  * the "designed, not built" blocks each carry an evidence pointer to the file
    that records the decision, rendered into the page's own table.

Regenerate after changing the feature registry or re-running the benchmarks.
The figures are plain SVG with no script and no external reference: they survive
the `material/privacy` plugin, inline cleanly into the page (so they inherit the
light/dark palette), and animate from `docs/assets/extra.css`.

Two things here are checks rather than judgement calls:

  * `fit()` refuses to emit a label wider than the shape holding it, so a
    clipped or overflowing label fails generation instead of shipping;
  * the colours were validated for lightness band, chroma, colour-vision
    separation and contrast against both Material surfaces this site renders on
    (light #ffffff, slate #1e2129) — see `docs/assets/extra.css`.

The canvas width matches the rendered content column (757 px measured), so the
type renders at roughly its authored size instead of being scaled down into
illegibility.
"""
from __future__ import annotations

import re
from pathlib import Path

from yazses.config import Config
from yazses.system.features import grouped_features

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = DOCS / "assets" / "arch"

BANNER = "<!-- GENERATED by scripts/gen-arch-figures.py — do not edit by hand. -->"

#: Canvas width every figure shares. The docs content column measures 757 px on
#: a wide viewport, so authoring at 760 keeps text at ~1:1 rather than scaled.
W = 760

# Type sizes, in the same units. Kept here so the fit checks and the CSS agree.
SZ_L, SZ_S, SZ_M, SZ_V, SZ_BAND = 13.0, 11.0, 10.5, 12.0, 10.0


# --------------------------------------------------------------------------- #
# Inputs
# --------------------------------------------------------------------------- #
def read_benchmarks() -> dict:
    """Parse the measured numbers out of docs/benchmarks.md.

    Deliberately strict: if the tables move or are reworded this raises rather
    than silently emitting a figure that disagrees with the published page.
    """
    text = (DOCS / "benchmarks.md").read_text(encoding="utf-8")

    models: dict[str, dict[str, float]] = {}
    # | `base.en` **(default)** | 0.85 s | **1.56 s** | 3.53 s | 0.283 (…) |
    row = re.compile(
        r"^\|\s*`([a-z.]+)`[^|]*\|\s*\*{0,2}([\d.]+)\s*s\*{0,2}\s*\|"
        r"\s*\*{0,2}([\d.]+)\s*s\*{0,2}\s*\|\s*\*{0,2}([\d.]+)\s*s\*{0,2}\s*\|",
        re.M,
    )
    for name, cold, median, p95 in row.findall(text):
        models[name] = {
            "cold_s": float(cold),
            "median_ms": float(median) * 1000.0,
            "p95_ms": float(p95) * 1000.0,
        }
    for required in ("tiny.en", "base.en", "small.en"):
        if required not in models:
            raise SystemExit(
                f"docs/benchmarks.md: could not parse the speed row for {required!r} "
                "— has the table changed? Fix the parser in scripts/gen-arch-figures.py."
            )

    stages = {
        label: _stage_ms(text, label)
        for label in (
            "VAD gate",
            "Text cleaner",
            "Disfluency filter",
            "Command grammar (dictation)",
        )
    }
    overhead = _stage_ms(text, "**Total non-decode overhead**")

    if "i7-1370P" not in text:
        raise SystemExit(
            "docs/benchmarks.md no longer names the i7-1370P test machine; update "
            "the provenance string in scripts/gen-arch-figures.py."
        )
    machine = "measured: i7-1370P · int8 on CPU, no GPU"
    return {"models": models, "stages": stages, "overhead_ms": overhead, "machine": machine}


def _stage_ms(text: str, label: str) -> float:
    m = re.search(rf"^\|\s*{re.escape(label)}\s*\|\s*\*{{0,2}}([\d.]+)\s*ms", text, re.M)
    if not m:
        raise SystemExit(
            f"docs/benchmarks.md: could not find a timing row for {label!r} "
            "— fix the parser in scripts/gen-arch-figures.py."
        )
    return float(m.group(1))


def capability_rows() -> list[tuple[str, int, int]]:
    """(category, wired, designed-but-not-wired) straight from the live registry."""
    return [
        (name, sum(1 for f in feats if f.wired), sum(1 for f in feats if not f.wired))
        for name, _blurb, feats in grouped_features(Config())
    ]


def command_counts() -> tuple[int, int]:
    index = (DOCS / "command-index.md").read_text(encoding="utf-8")
    tops = re.findall(r"^## `yazses ([\w-]+)", index, re.M)
    subs = re.findall(r"^### `yazses ([\w-]+) ", index, re.M)
    if not tops:
        raise SystemExit("docs/command-index.md looks empty — run scripts/gen-docs.py first.")
    return len(tops), len(tops) - len(set(subs)) + len(subs)


# --------------------------------------------------------------------------- #
# SVG helpers
# --------------------------------------------------------------------------- #
#: Rough advance widths for the site's UI sans (Inter), as a fraction of the font
#: size. Only used to catch labels that would overflow their shape — it needs to
#: be slightly pessimistic, not typographically exact.
_NARROW = set("iltjfIr!.,:;'`|·()[]-")
_WIDE = set("MWmw@%—")


def est_width(s: str, size: float) -> float:
    total = 0.0
    for ch in s:
        if ch in _NARROW:
            total += 0.34
        elif ch in _WIDE:
            total += 0.92
        elif ch.isupper() or ch.isdigit():
            total += 0.64
        else:
            total += 0.55
    return total * size


def fit(s: str, size: float, avail: float, where: str) -> str:
    """Refuse to emit a label that would overflow the shape holding it."""
    w = est_width(s, size)
    if w > avail:
        raise SystemExit(
            f"{where}: label {s!r} needs ~{w:.0f}px at {size:g}px but only {avail:.0f}px "
            "is available. Shorten the label or widen the shape."
        )
    return s


def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def svg(name: str, height: float, title: str, desc: str, body: list[str]) -> str:
    """Wrap a body in a self-contained, accessible root <svg>.

    role="img" plus <title>/<desc> is what a screen reader announces; the page
    also carries a data table under every figure, so no value is reachable only
    from the graphic.
    """
    head = (
        f'<svg class="yz-fig yz-fig--{name}" viewBox="0 0 {W} {height:g}" '
        f'xmlns="http://www.w3.org/2000/svg" role="img" '
        f'aria-labelledby="{name}-t {name}-d">'
    )
    lines = [
        BANNER,
        head,
        f'<title id="{name}-t">{esc(title)}</title>',
        f'<desc id="{name}-d">{esc(desc)}</desc>',
        *body,
        "</svg>",
    ]
    # No blank lines: Python-Markdown must see one uninterrupted raw HTML block.
    return "\n".join(ln for ln in lines if ln.strip()) + "\n"


def text(x: float, y: float, s: str, cls: str = "yz-l", anchor: str = "start") -> str:
    a = f' text-anchor="{anchor}"' if anchor != "start" else ""
    return f'<text class="{cls}" x="{x:g}" y="{y:g}"{a}>{esc(s)}</text>'


def box(x: float, y: float, w: float, h: float, cls: str = "yz-box", rx: float = 7) -> str:
    return f'<rect class="{cls}" x="{x:g}" y="{y:g}" width="{w:g}" height="{h:g}" rx="{rx:g}"/>'


def tip(s: str) -> str:
    """A native SVG tooltip — the hover layer, with no script."""
    return f"<title>{esc(s)}</title>"


def hline(x1: float, x2: float, y: float) -> str:
    return f'<path class="yz-flow" d="M {x1:g} {y:g} L {x2:g} {y:g}" marker-end="url(#yz-arrow)"/>'


def vline(x: float, y1: float, y2: float) -> str:
    return f'<path class="yz-flow" d="M {x:g} {y1:g} L {x:g} {y2:g}" marker-end="url(#yz-arrow)"/>'


def vpacket(x: float, y1: float, y2: float, delay: float = 0.0) -> str:
    return (
        f'<circle class="yz-pkt yz-pkt--v" cx="{x:g}" cy="{y1:g}" r="3" '
        f'style="--yz-dist:{y2 - y1 - 7:g}px;--yz-delay:{delay:g}s"/>'
    )


def hpacket(x: float, y: float, dist: float, cls: str, delay: float = 0.0) -> str:
    return (
        f'<circle class="yz-pkt {cls}" cx="{x:g}" cy="{y:g}" r="4.5" '
        f'style="--yz-dist:{dist:g}px;--yz-delay:{delay:g}s"/>'
    )


def defs() -> str:
    return (
        '<defs><marker id="yz-arrow" viewBox="0 0 10 10" refX="8.5" refY="5" '
        'markerWidth="5" markerHeight="5" orient="auto-start-reverse">'
        '<path class="yz-arrowhead" d="M 0 1.5 L 8.5 5 L 0 8.5 z"/></marker></defs>'
    )


def band(y_mid: float, label: str, gutter: float) -> str:
    fit(label, SZ_BAND, gutter, "band label")
    return text(gutter, y_mid + 3.5, label, "yz-band", "end")


def cell(x: float, y: float, w: float, h: float, head: str, sub: str, hover: str,
         cls: str = "yz-box", where: str = "cell") -> list[str]:
    """A labelled block: one bold line, one quiet line, both fit-checked."""
    pad = 14
    fit(head, SZ_L, w - pad, where)
    fit(sub, SZ_S, w - pad, where)
    return [
        f'<g class="yz-node">{tip(hover)}',
        box(x, y, w, h, cls),
        text(x + w / 2, y + h / 2 - 2, head, "yz-l", "middle"),
        text(x + w / 2, y + h / 2 + 14, sub, "yz-s", "middle"),
        "</g>",
    ]


def spread(x: float, total_w: float, n: int, gap: float) -> tuple[float, list[float]]:
    """Column width and left edges for n equal blocks across total_w."""
    w = (total_w - gap * (n - 1)) / n
    return w, [x + i * (w + gap) for i in range(n)]



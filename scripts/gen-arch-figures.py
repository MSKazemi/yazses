# --------------------------------------------------------------------------- #
# Figure 2 — the pipeline, coloured by measured cost
# --------------------------------------------------------------------------- #
def fig_pipeline(bench: dict) -> str:
    st = bench["stages"]
    decode = bench["models"]["base.en"]["median_ms"]
    overhead = bench["overhead_ms"]
    total = decode + overhead
    b: list[str] = [defs()]

    # Nine stages; five are separately timed. The other four say so rather than
    # being given a number nobody measured.
    stages = [
        ("Hotkey", "hold starts it", None),
        ("Capture", "mic → buffer", None),
        ("VAD gate", "drop silence", st["VAD gate"]),
        ("Padding", "lead-in", None),
        ("Decode", "faster-whisper", decode),
        ("Cleaner", "strip artefacts", st["Text cleaner"]),
        ("Disfluency", "fillers, repeats", st["Disfluency filter"]),
        ("Grammar", "text or command", st["Command grammar (dictation)"]),
        ("Inject", "into the app", None),
    ]

    def draw(items, x0, y, cw, gap, tag):
        for i, (name, sub, ms) in enumerate(items):
            x = x0 + i * (cw + gap)
            if ms is None:
                grp, cls = "yz-node yz-untimed", "yz-box yz-box--untimed"
                label, hover = "not timed", f"{name} — not separately timed"
            else:
                # Sequential ramp by order of magnitude. The decode is the only
                # hot cell, which is the finding rather than a styling choice.
                step = 7 if ms > 100 else 2
                grp, cls = f"yz-node yz-heat--{step}", "yz-box yz-heat-fill"
                label = f"{ms / 1000:.2f} s" if ms >= 100 else f"{ms:.3f} ms"
                hover = f"{name} — median {label}, {ms / total * 100:.2f}% of the burst"
            fit(name, SZ_L, cw - 12, tag)
            fit(sub, SZ_S, cw - 12, tag)
            b.append(f'<g class="{grp}">{tip(hover)}')
            b.append(box(x, y, cw, 74, cls))
            b.append(text(x + cw / 2, y + 26, name, "yz-l yz-on-heat", "middle"))
            b.append(text(x + cw / 2, y + 43, sub, "yz-s yz-on-heat", "middle"))
            b.append(text(x + cw / 2, y + 63, label, "yz-v yz-on-heat", "middle"))
            b.append("</g>")
            if i:
                b.append(hline(x - gap, x - 2, y + 37))

    x0, avail = 18, W - 36
    cw1 = (avail - 4 * 8) / 5
    cw2 = (avail - 3 * 8) / 4
    draw(stages[:5], x0, 30, cw1, 8, "pipeline row 1")
    draw(stages[5:], x0, 132, cw2, 8, "pipeline row 2")
    b.append(hpacket(x0 + cw1 / 2, 67, 4 * (cw1 + 8), "yz-pkt--h1"))
    b.append(hpacket(x0 + cw2 / 2, 169, 3 * (cw2 + 8), "yz-pkt--h2"))
    b.append(
        f'<path class="yz-flow" d="M {W - 18 - cw1 / 2:g} 104 L {W - 18 - cw1 / 2:g} 118 '
        f'L {x0 + cw2 / 2:g} 118 L {x0 + cw2 / 2:g} 130" marker-end="url(#yz-arrow)"/>'
    )

    # ---- the same burst, drawn to scale -----------------------------------
    rx, rw = 18, W - 36
    b.append(text(rx, 240, f"The same burst drawn to scale — {total / 1000:.2f} s end to end", "yz-l"))
    b.append(f'<g class="yz-node yz-heat--7">{tip(f"faster-whisper base.en decode: {decode:.0f} ms of {total:.0f} ms")}')
    b.append(box(rx, 250, rw, 28, "yz-bar yz-heat-fill", 4))
    b.append(text(rx + 12, 269, f"Decode — {decode / 1000:.2f} s · {decode / total * 100:.2f}%", "yz-v yz-on-heat"))
    b.append("</g>")

    # The non-decode sliver is a fifth of a pixel at this scale, so it is
    # magnified rather than drawn, and the magnification is stated on the figure.
    sliver = overhead / total * rw
    factor = 5000
    b.append(f'<path class="yz-lead" d="M {rx + rw - 1:g} 278 L {rx + rw - 1:g} 296 L {W - 250:g} 296"/>')
    b.append(text(W - 246, 292, f"everything else: {overhead:.2f} ms — {sliver:.2f} px wide here", "yz-s yz-halo"))

    mw = W - 300
    scale = mw / overhead
    order = [
        ("Disfluency filter", st["Disfluency filter"]),
        ("Command grammar", st["Command grammar (dictation)"]),
        ("VAD gate", st["VAD gate"]),
        ("Text cleaner", st["Text cleaner"]),
    ]
    b.append(text(rx, 328, f"That 0.29 ms, magnified ×{factor:,}", "yz-l"))
    cx = rx
    for i, (name, ms) in enumerate(order):
        seg = ms * scale
        b.append(f'<g class="yz-node yz-heat--{4 - i}">{tip(f"{name} — median {ms:.4f} ms")}')
        # A 2 px surface gap between segments, never a stroke around them.
        b.append(box(cx, 336, max(seg - 2, 1), 24, "yz-bar yz-heat-fill", 3))
        b.append("</g>")
        cx += seg
    b.append(
        text(rx, 378, " · ".join(f"{n} {ms:.3f}" for n, ms in order) + " ms", "yz-s")
    )
    b.append(
        text(
            rx,
            400,
            f"All non-decode work is {overhead / total * 100:.2f}% of a burst. Optimising anything "
            "but the speech model would not be measurable.",
            "yz-s",
        )
    )
    b.append(text(W - 18, 418, bench["machine"], "yz-m", "end"))

    return svg(
        "pipeline-heat",
        430,
        "The dictation pipeline, coloured by measured cost",
        "Nine stages in order: hotkey, capture, VAD gate, padding, decode, cleaner, disfluency "
        "filter, command grammar, injection. Five are separately timed; the other four are marked "
        f"as not timed. The decode takes {decode:.0f} milliseconds and every other measured stage "
        f"together takes {overhead:.2f} milliseconds — {overhead / total * 100:.2f}% of the burst. "
        "A scale ribbon shows the decode filling essentially the whole burst, with the remainder "
        f"magnified {factor} times to be visible at all.",
        b,
    )


# --------------------------------------------------------------------------- #
# Figure 3 — the daemon state machine
# --------------------------------------------------------------------------- #
#: Every transition here was read off `core/daemon.py`. Mermaid's automatic
#: layout turns this hub-and-spoke shape into overlapping labels, so it is laid
#: out by hand — and laying it out by hand is also what makes room to be honest
#: about the two states the daemon never actually enters.
def fig_states() -> str:
    b: list[str] = [defs()]
    spine = [
        ("LOADING", "model loading"),
        ("IDLE", "waiting"),
        ("RECORDING", "key held"),
        ("TRANSCRIBING", "decoding"),
        ("INJECTING", "typing"),
    ]
    x0, nw, gap, ny, nh = 21, 118, 32, 58, 38
    xs = [x0 + i * (nw + gap) for i in range(5)]
    mids = [x + nw / 2 for x in xs]

    # The loop back to IDLE, routed above the spine so it never fights the
    # branch bus below it.
    b.append(
        f'<path class="yz-flow" d="M {mids[4]:g} {ny:g} L {mids[4]:g} 32 L {mids[1]:g} 32 '
        f'L {mids[1]:g} {ny - 2:g}" marker-end="url(#yz-arrow)"/>'
    )
    b.append(text((mids[1] + mids[4]) / 2, 27, "typed — back to idle", "yz-s yz-halo", "middle"))

    for i, (name, sub) in enumerate(spine):
        fit(name, SZ_L, nw - 10, "state")
        fit(sub, SZ_S, nw - 10, "state")
        b.append(f'<g class="yz-node">{tip(f"{name} — {sub}")}')
        b.append(
            f'<rect class="yz-box yz-state" x="{xs[i]:g}" y="{ny:g}" width="{nw:g}" '
            f'height="{nh:g}" rx="7" style="--yz-delay:{i:g}s"/>'
        )
        b.append(text(mids[i], ny + 17, name, "yz-l", "middle"))
        b.append(text(mids[i], ny + 31, sub, "yz-s", "middle"))
        b.append("</g>")
        if i:
            b.append(hline(xs[i] - gap, xs[i] - 2, ny + nh / 2))

    for i, label in enumerate(["model loaded", "key held", "released", "text ready"]):
        cxx = (xs[i] + nw + xs[i + 1]) / 2
        # These sit above the boxes, so they may overhang a node; the real limit
        # is the distance to the next transition label.
        fit(label, SZ_S, nw + gap - 20, "transition label")
        b.append(text(cxx, ny - 6, label, "yz-s yz-halo", "middle"))

    # The two early exits back to IDLE.
    for src, drop, land, label in (
        (mids[2], 116, 250, "silent audio, discarded"),
        (mids[3], 138, 268, "nothing to type"),
    ):
        b.append(
            f'<path class="yz-flow" d="M {src:g} {ny + nh:g} L {src:g} {drop:g} L {land:g} {drop:g} '
            f'L {land:g} {ny + nh + 2:g}" marker-end="url(#yz-arrow)"/>'
        )
        b.append(text((src + land) / 2, drop + 4, label, "yz-s yz-halo", "middle"))

    # Modes: entered deliberately over IPC, never by the hotkey.
    modes = [
        ("MEETING", "yazses meeting start", "Hands-free whole-meeting capture; stopping it finalizes through TRANSCRIBING"),
        ("REMOTE", "SETUP → ACTIVE", "REMOTE_SETUP opens the SSH tunnel, then REMOTE_ACTIVE forwards text to the agent on the other host"),
        ("ENROLLING", "yazses enroll", "The accessibility and microphone calibration wizard"),
        ("READBACK", "speak it back", "Reads a transcript aloud through offline TTS"),
    ]
    mw, mxs = spread(x0, W - 2 * x0, 4, 18)
    mmid = [x + mw / 2 for x in mxs]
    bus_y, my = 162, 180
    b.append(f'<path class="yz-flow" d="M 200 {ny + nh:g} L 200 {bus_y:g}"/>')
    b.append(f'<path class="yz-flow" d="M {mmid[0]:g} {bus_y:g} L {mmid[-1]:g} {bus_y:g}"/>')
    for i, (name, sub, hover) in enumerate(modes):
        b.append(f'<path class="yz-flow" d="M {mmid[i]:g} {bus_y:g} L {mmid[i]:g} {my - 2:g}" marker-end="url(#yz-arrow)"/>')
        b += cell(mxs[i], my, mw, 44, name, sub, hover, "yz-box yz-box--chip", "mode")
    b.append(text(x0, 248, "Modes are entered over IPC, never by the hotkey, and each returns to IDLE when it finishes.", "yz-s"))

    # The two states in the enum that the daemon never sets. A tidier diagram
    # would quietly imply it does.
    gy = 274
    for i, (name, note) in enumerate((("ERROR", "set by the tray"), ("PAUSED", "never set"))):
        gx = x0 + i * 150
        b.append(f'<g class="yz-node">{tip(f"{name} — {note}")}')
        b.append(box(gx, gy, 138, 36, "yz-box yz-box--untimed"))
        b.append(text(gx + 69, gy + 16, name, "yz-l yz-ghost", "middle"))
        b.append(text(gx + 69, gy + 29, note, "yz-s", "middle"))
        b.append("</g>")
    b.append(text(x0 + 316, gy + 14, "In the type, but not states the daemon enters. ERROR is what the tray shows", "yz-s"))
    b.append(text(x0 + 316, gy + 30, "when the daemon stops answering IPC; nothing currently sets PAUSED.", "yz-s"))

    return svg(
        "states",
        326,
        "The daemon state machine",
        "A spine of five states carries ordinary dictation: LOADING to IDLE once the model is "
        "loaded, IDLE to RECORDING when the key is held, RECORDING to TRANSCRIBING when it is "
        "released, TRANSCRIBING to INJECTING when text is ready, and INJECTING back to IDLE. Two "
        "early exits return to IDLE: from RECORDING when the audio was silent, and from "
        "TRANSCRIBING when there was nothing to type. Four further modes hang off IDLE and are "
        "entered over IPC rather than by the hotkey: MEETING, REMOTE_SETUP into REMOTE_ACTIVE, "
        "ENROLLING and READBACK; each returns to IDLE. Two more states exist in the type but are "
        "not entered by the daemon: ERROR is set by the tray when the daemon stops answering, and "
        "nothing currently sets PAUSED.",
        b,
    )



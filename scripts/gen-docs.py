#!/usr/bin/env python3
"""Generate the reference docs that must never drift from the code:

  docs/features.md        every capability, grouped by category (from features.py)
  docs/configuration.md   every config.toml section + key + default (from config.py)
  docs/command-index.md   every CLI command + options (from the Typer/Click app)

These three are the "reference document for all commands and features". They are
regenerated (never hand-edited) so they stay in lockstep with the registry and the
CLI. Run:  uv run python scripts/gen-docs.py

The prose docs (architecture, roadmap, troubleshooting, how-to) are hand-written
and live alongside these.
"""
from __future__ import annotations

import ast
import dataclasses
import functools
import io
import sys
from pathlib import Path

import click
import typer

from yazses import branding
from yazses.config import Config
from yazses.system.features import grouped_features

sys.path.insert(0, str(Path(__file__).resolve().parent))
from config_status import inert_dotted_keys  # noqa: E402  (sibling script, not a package)

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"

_TIER_ORDER_NOTE = (
    "**Tiers:** `core` (always on) · `recommended (on by default)` · `recommended` "
    "(safe, worth enabling) · `optional` · `experimental` (rough edges — needs "
    "`--force` to enable) · `planned` (designed but not yet wired into this build — "
    "cannot be enabled yet; contributions welcome)."
)



def _download_mb(slug: str):
    """The feature's resolved download size in MB, or None (ADR-018).

    Reads the same committed table the CLI reads, so the feature reference and
    `yazses features info` can never quote different numbers.
    """
    try:
        from yazses.system.depsize import full_download_mb

        return full_download_mb(slug)
    except Exception:
        return None


def _format_mb(mb: float) -> str:
    from yazses.system.depsize import format_mb

    return format_mb(mb)


def _front(title: str, desc: str) -> str:
    return (
        "---\n"
        f"title: {title}\n"
        f"description: {desc}\n"
        "---\n\n"
        f"<!-- GENERATED by scripts/gen-docs.py — do not edit by hand. -->\n\n"
        f"# {title}\n\n"
    )


# --------------------------------------------------------------------------- #
# docs/features.md
# --------------------------------------------------------------------------- #
def gen_features() -> str:
    cfg = Config()
    groups = grouped_features(cfg)
    total = sum(len(f) for _c, _b, f in groups)

    out = io.StringIO()
    out.write(_front("Feature Reference",
                     f"All {total} YazSes capabilities, what each does, and how to turn it on."))
    out.write(
        f"YazSes ships **{total} capabilities**. All but the core are **off by default** — "
        "turn one on with `yazses features enable <toggle>` and apply with `yazses restart`. "
        "Browse them interactively with `yazses features` (grouped) or `yazses features info "
        "<toggle>` (one card).\n\n"
    )
    out.write(_TIER_ORDER_NOTE + "\n\n")

    # table of contents
    out.write("## Contents\n\n")
    for cat, _blurb, feats in groups:
        anchor = cat.lower().replace(" & ", "--").replace(" ", "-").replace(",", "")
        out.write(f"- [{cat}](#{anchor}) ({len(feats)})\n")
    out.write("\n")

    for cat, blurb, feats in groups:
        out.write(f"## {cat}\n\n")
        if blurb:
            out.write(f"*{blurb}*\n\n")
        for f in feats:
            toggle = f.slug if f.toggleable else "—"
            out.write(f"### {f.name}\n\n")
            out.write(f"- **Toggle:** `{toggle}`  ·  **Tier:** {f.tier_label}")
            if f.note:
                out.write(f"  ·  **Config:** `{f.note}`")
            out.write("\n")
            if f.why:
                out.write(f"- **What it does:** {f.why}\n")
            if f.use_case:
                out.write(f"- **Use when:** {f.use_case}\n")
            if f.example:
                out.write(f"- **Example:** {f.example}\n")
            # What it costs to turn on (ADR-018). Only for features that actually
            # fetch something -- a "Download: 0 MB" line on the 126 pure-logic
            # capabilities would be noise, and the absence already says free.
            _mb = _download_mb(f.slug)
            if _mb:
                out.write(f"- **Download:** {_format_mb(_mb)}\n")
            if not f.wired:
                out.write(
                    "- **Activate:** not possible yet — designed but not wired "
                    "into this build (`yazses features enable` refuses it; "
                    "contributions welcome)\n"
                )
            elif f.toggleable:
                out.write(
                    f"- **Activate:** `yazses features enable {f.slug}` "
                    "then `yazses restart`\n"
                )
            else:
                out.write("- **Activate:** always on (cannot be disabled)\n")
            out.write("\n")
    return out.getvalue()



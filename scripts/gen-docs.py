#!/usr/bin/env python3
"""Generate the reference docs that must never drift from the code:

  docs/features.md        every capability, grouped by category (from features.py)
  docs/configuration.md   every config.toml section + key + default (from config.py)
  docs/command-index.md   every CLI command + options (from the Typer/Click app)
  src/yazses/config_sections.py
                          every `[section]` name (from config.py), so `cli.main()` can
                          escape them in `--help` without importing `yazses.config`

The first three are the "reference document for all commands and features". All four
are regenerated (never hand-edited) so they stay in lockstep with the registry and the
CLI. Run:  uv run python scripts/gen-docs.py

The prose docs (architecture, roadmap, troubleshooting, how-to) are hand-written
and live alongside these. The one part of them this script touches is a registry
count: a hand-written page that states how many capabilities exist, are wired, or are
designed but not built writes the number between `<!-- registry:KIND -->` and
`<!-- /registry -->`, and `fill_registry_counts` rewrites only that number (see
`REGISTRY_COUNT_PAGES`).
"""

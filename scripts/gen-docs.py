# docs/command-index.md
# --------------------------------------------------------------------------- #
def _walk_click(cmd: click.Command, name: str, depth: int, out: io.StringIO) -> None:
    prefix = "yazses " + name if name else "yazses"
    heading = "#" * min(depth + 1, 6)
    out.write(f"{heading} `{prefix}`\n\n")
    if cmd.help:
        out.write(cmd.help.strip().split("\n\n")[0].strip() + "\n\n")
    # Typer >=0.13 vendors its own click fork, so isinstance against upstream
    # ``click`` no longer matches. Duck-type on the stable ``param_type_name`` API.
    params = [p for p in cmd.params if p.param_type_name == "option"]
    args = [p for p in cmd.params if p.param_type_name == "argument"]
    if args:
        out.write("- **Arguments:** " + ", ".join(f"`{a.name}`" for a in args) + "\n")
    for opt in params:
        if opt.name in ("help",):
            continue
        flags = ", ".join(f"`{o}`" for o in opt.opts + opt.secondary_opts)
        help_txt = (opt.help or "").strip()
        out.write(f"- {flags} — {help_txt}\n")
    if args or [p for p in params if p.name != "help"]:
        out.write("\n")
    if hasattr(cmd, "commands"):
        for sub_name in sorted(cmd.commands):
            child = cmd.commands[sub_name]
            full = f"{name} {sub_name}".strip()
            _walk_click(child, full, depth + 1, out)


def gen_command_index() -> str:
    from yazses.cli import app

    click_app = typer.main.get_command(app)
    out = io.StringIO()
    out.write(_front("Command Index",
                     "Every yazses CLI command and option, generated from the app."))
    out.write(
        "The complete command tree. For grouped, example-rich help run `yazses --help` "
        "or `yazses <command> --help`. See also the prose "
        "[CLI reference](cli-reference.md).\n\n"
    )
    # top-level commands (Click group)
    assert hasattr(click_app, "commands")
    for sub_name in sorted(click_app.commands):
        _walk_click(click_app.commands[sub_name], sub_name, 1, out)
    return out.getvalue()


def main() -> None:
    DOCS.mkdir(exist_ok=True)
    targets = {
        "features.md": gen_features(),
        "configuration.md": gen_configuration(),
        "command-index.md": gen_command_index(),
    }
    for fname, content in targets.items():
        (DOCS / fname).write_text(content, encoding="utf-8")
        print(f"wrote docs/{fname}  ({content.count(chr(10))} lines)")
    print(f"YazSes {branding.version()} — reference docs regenerated.")


if __name__ == "__main__":
    main()
